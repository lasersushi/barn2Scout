// Writes supabase/seed.sql: test accounts plus SAMPLE scouting data for a
// local Supabase stack (`supabase start`), so the AI features have something
// to read. Local testing only; nothing here touches the real project.
//
// Run from the repo root, then reset the local database to apply it:
//   dart run tool/generate_local_seed.dart
//   supabase db reset
//
// The event is a real 2026 event 751 played (from the backtest fixtures), so
// TBA's schedule and stats line up with the sample reports. The reports
// themselves are made up: each team gets a play style, mostly matching its
// real OPR, and a few deliberately don't, so the picklist review has
// disagreements to find.

import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;

const _event = '2026cacac';
const _fixture = 'test/fixtures/backtest/$_event.json';
const _out = 'supabase/seed.sql';

/// Shared password for every local test account.
const _password = 'barn2-local-test';

/// Fixed ids so re-running gives the same seed.
const _scoutId = '00000000-0000-4000-8000-000000000001';
const _aiScoutId = '00000000-0000-4000-8000-000000000002';
const _adminId = '00000000-0000-4000-8000-000000000003';

const _accounts = [
  (_scoutId, 'scout@priorypanther.com', 'Test Scout', 'scout', false),
  (_aiScoutId, 'ai-scout@priorypanther.com', 'Test AI Scout', 'scout', true),
  // @prioryca.org signs in as a super admin in the app (AuthCubit).
  (_adminId, 'admin@prioryca.org', 'Test Admin', 'super_admin', false),
];

enum _Style { elite, solid, defender, unreliable, weak }

void main() {
  final fixture =
      jsonDecode(File(_fixture).readAsStringSync()) as Map<String, dynamic>;
  final oprs = (fixture['tbaOprs'] as Map<String, dynamic>)
      .map((k, v) => MapEntry(int.parse(k.substring(3)), (v as num).toDouble()));
  final matches = [
    for (final m in fixture['matches'] as List)
      if ((m as Map<String, dynamic>)['comp_level'] == 'qm') m,
  ]..sort((a, b) =>
      (a['match_number'] as int).compareTo(b['match_number'] as int));

  final rng = math.Random(751);
  final styles = _assignStyles(oprs);

  final sql = StringBuffer()
    ..writeln('-- GENERATED by tool/generate_local_seed.dart. Do not edit by hand.')
    ..writeln('-- LOCAL TESTING ONLY. Test accounts (password "$_password"):')
    ..writeln('--   ${_accounts.map((a) => a.$2).join(', ')}')
    ..writeln('-- Scouting reports below are SAMPLE DATA for $_event, not real.')
    ..writeln();

  // ── Accounts ───────────────────────────────────────────────────────────────
  for (final (id, email, name, role, ai) in _accounts) {
    sql
      ..writeln('insert into auth.users (instance_id, id, aud, role, email, '
          'encrypted_password, email_confirmed_at, raw_app_meta_data, '
          'raw_user_meta_data, created_at, updated_at, confirmation_token, '
          'email_change, email_change_token_new, recovery_token) values ('
          "'00000000-0000-0000-0000-000000000000', '$id', 'authenticated', "
          "'authenticated', '$email', "
          "extensions.crypt('$_password', extensions.gen_salt('bf')), now(), "
          "'{\"provider\":\"email\",\"providers\":[\"email\"]}', '{}', now(), "
          "now(), '', '', '', '');")
      ..writeln('insert into auth.identities (id, user_id, provider_id, '
          'identity_data, provider, last_sign_in_at, created_at, updated_at) '
          "values ('$id', '$id', '$id', "
          "'{\"sub\":\"$id\",\"email\":\"$email\",\"email_verified\":true}', "
          "'email', now(), now(), now());")
      ..writeln("update public.profiles set display_name = '$name', "
          "role = '$role', ai_access = $ai where id = '$id';")
      ..writeln();
  }

  // ── Match reports: every team in every qual ────────────────────────────────
  final rows = <String>[];
  var n = 0;
  for (final m in matches) {
    final alliances = m['alliances'] as Map<String, dynamic>;
    final when = DateTime.fromMillisecondsSinceEpoch(
        ((m['actual_time'] ?? m['time']) as int) * 1000,
        isUtc: true);
    for (final side in ['red', 'blue']) {
      for (final key in (alliances[side]['team_keys'] as List).cast<String>()) {
        final team = int.tryParse(key.substring(3));
        if (team == null) continue;
        final style = styles[team] ?? _Style.solid;
        final r = _report(style, rng);
        rows.add('(${_sqlUuid(++n)}, ${_sqlStr(_scoutId)}, $team, '
            '${m['match_number']}, ${_sqlStr(_event)}, '
            "'Sample data', ${_sqlStr(when.toIso8601String())}, "
            '${_jsonb(r.auto)}, ${_jsonb(r.teleop)}, ${_jsonb(r.endgame)}, '
            '${_sqlStr(r.notes)})');
      }
    }
  }
  sql
    ..writeln('insert into public.scouting_records (id, user_id, team_number, '
        'match_number, event_key, scouter_name, "timestamp", auto_data, '
        'teleop_data, endgame_data, notes) values')
    ..writeln('${rows.join(',\n')};')
    ..writeln();

  // ── One pit report per team ────────────────────────────────────────────────
  final pitRows = <String>[];
  final start = DateTime.parse(fixture['startDate'] as String).toUtc();
  for (final team in styles.keys.toList()..sort()) {
    final p = _pit(styles[team]!, rng);
    pitRows.add('(${_sqlUuid(++n)}, ${_sqlStr(_scoutId)}, $team, '
        "${_sqlStr(_event)}, 'Sample data', ${_sqlStr(start.toIso8601String())}, "
        '${_jsonb(p.data)}, ${_sqlStr(p.notes)})');
  }
  sql
    ..writeln('insert into public.pit_scouting_records (id, user_id, '
        'team_number, event_key, scouter_name, "timestamp", pit_data, notes) '
        'values')
    ..writeln('${pitRows.join(',\n')};');

  File(_out).writeAsStringSync(sql.toString());
  stdout.writeln('Wrote $_out: ${rows.length} match reports, '
      '${pitRows.length} pit reports for $_event.');
}

/// Mostly by OPR rank, with deliberate mismatches for the picklist review.
Map<int, _Style> _assignStyles(Map<int, double> oprs) {
  final ranked = oprs.keys.toList()..sort((a, b) => oprs[b]!.compareTo(oprs[a]!));
  final styles = <int, _Style>{};
  for (final (i, team) in ranked.indexed) {
    final f = i / ranked.length;
    styles[team] = f < 0.15
        ? _Style.elite
        : f < 0.5
            ? _Style.solid
            : f < 0.7
                ? _Style.defender
                : _Style.weak;
  }
  // Two strong-on-paper teams scouts saw break down, and a low-OPR team
  // scouts rate as a great defender.
  styles[ranked[2]] = _Style.unreliable;
  styles[ranked[6]] = _Style.unreliable;
  styles[ranked[ranked.length - 3]] = _Style.defender;
  return styles;
}

({Map<String, Object> auto, Map<String, Object> teleop, Map<String, Object> endgame, String notes})
    _report(_Style style, math.Random rng) {
  int around(int center) => (center + rng.nextInt(3) - 1).clamp(0, 5);
  T pick<T>(List<T> xs) => xs[rng.nextInt(xs.length)];
  final broke = style == _Style.unreliable && rng.nextDouble() < 0.4;

  final (auto, offense, defense, climbs, endgame) = switch (style) {
    _Style.elite => (5, 5, 1, ['L3', 'L3', 'L2'], 5),
    _Style.solid => (3, 3, 2, ['L2', 'L2', 'L1'], 3),
    _Style.defender => (2, 1, 5, ['L1', 'None'], 2),
    _Style.unreliable => (4, 4, 1, ['L3', 'L2'], 4),
    _Style.weak => (1, 1, 1, ['None', 'None', 'L1'], 1),
  };

  final notes = switch (style) {
    _ when broke => pick([
        'Robot died about 30 seconds into teleop, sat still the rest of the match.',
        'Disconnected in auto and never came back.',
        'Intake broke early, could only push.',
        'Tipped over going over the bump.',
      ]),
    _Style.elite => pick([
        'Very fast cycles, almost never missed.',
        'Carried the alliance. Drivers are excellent.',
        'Clean auto, climbed with time to spare.',
        '',
      ]),
    _Style.solid => pick(['Consistent, nothing fancy.', 'Decent shooter.', '', '']),
    _Style.defender => pick([
        'Played great defense on their best scorer the whole match.',
        'Pinned opponents without fouls, really smart defense.',
        'Barely scored but shut down the other alliance.',
        '',
      ]),
    _Style.unreliable => pick(['Scored a lot when it worked.', 'Fast when working.', '']),
    _Style.weak => pick([
        'Struggled to pick up game pieces.',
        'Mostly drove around.',
        'Missed most shots.',
        '',
      ]),
  };

  return (
    auto: {
      'auto_left_line': broke ? false : style != _Style.weak || rng.nextBool(),
      'auto_rating': broke ? 0 : around(auto),
    },
    teleop: {
      'teleop_offense': broke ? 0 : around(offense),
      'teleop_defense': around(defense),
    },
    endgame: {
      'endgame_climb': broke ? 'None' : pick(climbs),
      'endgame_rating': broke ? 0 : around(endgame),
    },
    notes: notes,
  );
}

({Map<String, Object> data, String notes}) _pit(_Style style, math.Random rng) {
  T pick<T>(List<T> xs) => xs[rng.nextInt(xs.length)];
  return (
    data: {
      'pit_drivetrain': style == _Style.weak ? pick(['Tank', 'Swerve']) : 'Swerve',
      'pit_weight': 100 + rng.nextInt(25),
      'pit_climb': switch (style) {
        _Style.elite || _Style.unreliable => 'L3',
        _Style.solid => 'L2',
        _ => pick(['None', 'L1']),
      },
      'pit_auto_leave': style != _Style.weak,
      'pit_observations': switch (style) {
        _Style.elite => 'Very polished robot, spare parts organized.',
        _Style.unreliable => 'Still rewiring between matches, said they had brownouts.',
        _Style.defender => 'Heavy, low robot built to push.',
        _Style.weak => 'Rookie-ish team, still tuning the intake.',
        _Style.solid => 'Simple, robust design.',
      },
    },
    notes: '',
  );
}

String _sqlStr(String s) => "'${s.replaceAll("'", "''")}'";
String _jsonb(Object o) => '${_sqlStr(jsonEncode(o))}::jsonb';

/// Deterministic, valid v4-shaped UUID for row [n].
String _sqlUuid(int n) {
  final hex = n.toRadixString(16).padLeft(12, '0');
  return _sqlStr('5eed0000-0000-4000-8000-$hex');
}
